#!/usr/bin/env python3
"""
Generate the API reference of the SDK from its source: one Markdown page per class with its fields,
enums, methods (signature, description, API endpoint) and cross references to the other classes.

The source is read with ``ast`` (nothing is imported or called), so the output only depends on the code.

Usage::

    python docs/generate_api_docs.py              # write docs/api/ and the class table in README.md
    python docs/generate_api_docs.py --check      # exit 1 if docs/api/ or README.md are out of date
    python docs/generate_api_docs.py --wiki DIR   # write the same pages for the GitHub wiki into DIR

Run it after changing a class, a method signature, a docstring or an enum; a unit test fails while the
committed pages differ from the generated ones.
"""
import argparse
import ast
import os
import re
import sys
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Set, Tuple

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SRC = os.path.join(ROOT, 'src', 'xurrent')
DOCS = os.path.join(ROOT, 'docs', 'api')
README = os.path.join(ROOT, 'README.md')
REPO_URL = 'https://github.com/fasteiner/xurrent-python'
API_DOCS = 'https://developer.xurrent.com/v1'
CORE = 'XurrentApiHelper'
README_START = '<!-- api-reference:start -->'
README_END = '<!-- api-reference:end -->'
GENERATED = '<!-- Generated by docs/generate_api_docs.py from the source code; do not edit by hand. -->'


# ----------------------------------------------------------------------------------------------------
# Model
# ----------------------------------------------------------------------------------------------------

@dataclass
class EnumInfo:
    name: str
    module: str
    doc: str
    members: List[Tuple[str, str]]          # (value, comment)
    owner: Optional[str] = None             # page the enum is documented on


@dataclass
class MethodInfo:
    name: str
    kind: str                               # 'class', 'static' or 'instance'
    signature: str
    doc: str
    endpoint: Optional[str]
    returns: List[str]                      # classes it returns or reads
    enums: List[str]                        # enums in its parameters


@dataclass
class FieldInfo:
    name: str
    annotation: str
    default: str
    target: Optional[str] = None            # class or enum the value is converted to


@dataclass
class ClassInfo:
    name: str
    module: str
    doc: str
    resource: Optional[str]
    api_docs: Optional[str]
    fields: List[FieldInfo] = field(default_factory=list)
    methods: List[MethodInfo] = field(default_factory=list)
    init_signature: str = ''
    init_doc: str = ''
    enums: List[str] = field(default_factory=list)


# ----------------------------------------------------------------------------------------------------
# Reading the source
# ----------------------------------------------------------------------------------------------------

def _base_names(node: ast.ClassDef) -> Set[str]:
    return {ast.unparse(base).split('.')[-1] for base in node.bases}


def _assigned_string(node: ast.ClassDef, name: str) -> Optional[str]:
    for item in node.body:
        if (isinstance(item, ast.Assign) and len(item.targets) == 1 and isinstance(item.targets[0], ast.Name)
                and item.targets[0].id == name and isinstance(item.value, ast.Constant)):
            return item.value.value
    return None


def _enum(node: ast.ClassDef, module: str, lines: List[str]) -> EnumInfo:
    members = []
    for item in node.body:
        if (isinstance(item, ast.Assign) and len(item.targets) == 1 and isinstance(item.targets[0], ast.Name)
                and isinstance(item.value, ast.Constant) and isinstance(item.value.value, str)):
            line = lines[item.lineno - 1][item.value.end_col_offset:]
            match = re.search(r'#\s*(.*\S)', line)
            members.append((item.value.value, match.group(1) if match else ''))
    return EnumInfo(node.name, module, ast.get_docstring(node) or '', members)


def _signature(func: ast.FunctionDef, kind: str) -> Tuple[str, List[ast.arg]]:
    args = func.args
    positional = args.posonlyargs + args.args
    defaults = [None] * (len(positional) - len(args.defaults)) + list(args.defaults)
    parts, params = [], []
    for index, (arg, default) in enumerate(zip(positional, defaults)):
        if index == 0 and kind in ('class', 'instance'):
            continue                        # cls / self
        params.append(arg)
        text = arg.arg
        if arg.annotation is not None:
            text += f': {ast.unparse(arg.annotation)}'
        if default is not None:
            text += f' = {ast.unparse(default)}' if arg.annotation is not None else f'={ast.unparse(default)}'
        parts.append(text)
    if args.vararg:
        parts.append(f'*{args.vararg.arg}')
    for arg, default in zip(args.kwonlyargs, args.kw_defaults):
        params.append(arg)
        text = arg.arg + (f': {ast.unparse(arg.annotation)}' if arg.annotation is not None else '')
        parts.append(text + (f' = {ast.unparse(default)}' if default is not None else ''))
    if args.kwarg:
        parts.append(f'**{args.kwarg.arg}')
    returns = f' -> {ast.unparse(func.returns)}' if func.returns is not None else ''
    return f"{func.name}({', '.join(parts)}){returns}", params


def _path(node: ast.expr, resource: Optional[str]) -> Optional[str]:
    """The URL path an expression builds, e.g. f'{base_url}/{cls.__resourceUrl__}/{id}' -> /requests/{id}."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        text = node.value
    elif isinstance(node, ast.JoinedStr):
        text = ''
        for value in node.values:
            if isinstance(value, ast.Constant):
                text += str(value.value)
                continue
            expr = ast.unparse(value.value)
            if expr.endswith('base_url'):
                continue
            if expr.endswith('__resourceUrl__'):
                text += resource or '{resource}'
            elif expr == 'self.id':
                text += '{id}'
            else:
                text += '{' + expr.split('.')[-1] + '}'
    else:
        return None
    text = text.split('?')[0]
    return text if text.startswith('/') else None


def _endpoint(func: ast.FunctionDef, resource: Optional[str]) -> Optional[str]:
    uri = None
    for node in ast.walk(func):
        if (isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name)
                and node.targets[0].id == 'uri'):
            uri = _path(node.value, resource)
            break
    for node in ast.walk(func):
        if not isinstance(node, ast.Call):
            continue
        name = node.func.attr if isinstance(node.func, ast.Attribute) else getattr(node.func, 'id', None)
        if name == 'api_call':
            if uri is None and node.args:
                uri = _path(node.args[0], resource)
            method = 'GET'
            if len(node.args) > 1 and isinstance(node.args[1], ast.Constant):
                method = str(node.args[1].value).upper()
            for keyword in node.keywords:
                if keyword.arg == 'method' and isinstance(keyword.value, ast.Constant):
                    method = str(keyword.value.value).upper()
            return f'{method} {uri}' if uri else None
        if name == 'list_notes':
            return f'GET {uri}' if uri else None
    return None


def _names_in(node: Optional[ast.AST]) -> Set[str]:
    """Identifiers in an annotation, including those inside string annotations such as 'List[Task]'."""
    names: Set[str] = set()
    if node is None:
        return names
    for child in ast.walk(node):
        if isinstance(child, ast.Name):
            names.add(child.id)
        elif isinstance(child, ast.Constant) and isinstance(child.value, str):
            names.update(re.findall(r'[A-Za-z_]\w*', child.value))
    return names


def _used_classes(func: ast.FunctionDef) -> List[str]:
    """Classes the function calls (X.from_data, X.get_by_id, X(...)), in order of appearance."""
    used: List[str] = []
    for node in ast.walk(func):
        if isinstance(node, ast.Call):
            target = node.func.value if isinstance(node.func, ast.Attribute) else node.func
            if isinstance(target, ast.Name) and target.id not in used:
                used.append(target.id)
    return used


def read_package(src: str = SRC):
    """(classes, enums) of the package: ClassInfo per documented class and EnumInfo per enum."""
    parsed = []
    for filename in sorted(os.listdir(src)):
        if not filename.endswith('.py') or filename == '__init__.py':
            continue
        path = os.path.join(src, filename)
        with open(path, encoding='utf-8') as file:
            source = file.read()
        parsed.append((filename[:-3], source, ast.parse(source)))

    enums: Dict[str, EnumInfo] = {}
    class_nodes = []
    for module, source, tree in parsed:
        lines = source.splitlines()
        for node in tree.body:
            if not isinstance(node, ast.ClassDef):
                continue
            bases = _base_names(node)
            if 'Enum' in bases and node.name != 'LogLevel':
                enums[node.name] = _enum(node, module, lines)
            elif ('JsonSerializableDict' in bases and _assigned_string(node, '__resourceUrl__')) or node.name == CORE:
                class_nodes.append((module, source, node))

    known = {node.name for _, _, node in class_nodes}
    classes: List[ClassInfo] = []
    for module, source, node in class_nodes:
        resource = _assigned_string(node, '__resourceUrl__')
        segment = ast.get_source_segment(source, node) or ''
        match = re.search(r'#\s*(https://developer\.xurrent\.com/\S+)', segment)
        info = ClassInfo(node.name, module, ast.get_docstring(node) or '', resource,
                         match.group(1) if match else (f'{API_DOCS}/{resource}/' if resource else None))
        for item in node.body:
            if not isinstance(item, ast.FunctionDef):
                continue
            decorators = {ast.unparse(d) for d in item.decorator_list}
            kind = 'class' if 'classmethod' in decorators else 'static' if 'staticmethod' in decorators else 'instance'
            if item.name == '__init__':
                info.fields = _fields(item, known, enums)
                info.init_signature = _signature(item, 'instance')[0].replace('__init__', node.name, 1)
                info.init_doc = ast.get_docstring(item) or ''
                continue
            if item.name.startswith('_') or item.name == 'from_data':
                continue
            signature, params = _signature(item, kind)
            returns = [name for name in _used_classes(item) if name in known]
            for name in sorted(_names_in(item.returns)):
                resolved = node.name if name == 'T' else name
                if resolved in known and resolved not in returns:
                    returns.append(resolved)
            param_enums = sorted({name for param in params for name in _names_in(param.annotation) if name in enums})
            info.methods.append(MethodInfo(item.name, kind, signature, ast.get_docstring(item) or '',
                                           _endpoint(item, resource), returns, param_enums))
        info.enums = [name for name, enum in enums.items() if enum.module == module]
        classes.append(info)

    for info in classes:
        for name in info.enums:
            enums[name].owner = enums[name].owner or info.name
    return classes, enums


def _fields(init: ast.FunctionDef, known: Set[str], enums: Dict[str, EnumInfo]) -> List[FieldInfo]:
    args = init.args
    positional = args.args[1:]
    defaults = [None] * (len(positional) - len(args.defaults)) + list(args.defaults)
    targets: Dict[str, str] = {}
    for node in ast.walk(init):
        if not (isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Attribute)
                and isinstance(node.targets[0].value, ast.Name) and node.targets[0].value.id == 'self'):
            continue
        for call in ast.walk(node.value):
            if not isinstance(call, ast.Call):
                continue
            if (isinstance(call.func, ast.Attribute) and call.func.attr == 'from_data'
                    and isinstance(call.func.value, ast.Name) and call.func.value.id in known):
                targets[node.targets[0].attr] = call.func.value.id
            elif (isinstance(call.func, ast.Name) and call.func.id == 'enum_or_raw' and call.args
                  and isinstance(call.args[0], ast.Name) and call.args[0].id in enums):
                targets[node.targets[0].attr] = call.args[0].id
    result = []
    for arg, default in zip(positional, defaults):
        if arg.arg == 'connection_object':
            continue
        result.append(FieldInfo(arg.arg, ast.unparse(arg.annotation) if arg.annotation is not None else '',
                                ast.unparse(default) if default is not None else '', targets.get(arg.arg)))
    return result


# ----------------------------------------------------------------------------------------------------
# Rendering
# ----------------------------------------------------------------------------------------------------

class Links:
    """Link targets for the repository (Request.md) or the wiki (absolute URLs: GitHub serves the wiki home
    page at .../wiki without a trailing slash, where a relative link like "Request" would leave the wiki)."""

    def __init__(self, wiki: bool):
        self.wiki = wiki

    def page(self, name: str, anchor: str = '') -> str:
        target = f'{REPO_URL}/wiki/{name}' if self.wiki else f'{name}.md'
        return target + (f'#{anchor.lower()}' if anchor else '')

    def index(self) -> str:
        return f'{REPO_URL}/wiki' if self.wiki else 'README.md'


def _cell(text: str) -> str:
    return text.replace('|', '\\|').replace('\n', ' ')


def _instance_name(class_name: str) -> str:
    return re.sub(r'(?<!^)(?=[A-Z])', '_', class_name).lower()


def render_doc(doc: str) -> List[str]:
    """Docstring as Markdown: :param/:return lines as a list, doctest examples as code."""
    if not doc:
        return []
    out: List[str] = []
    params: List[str] = []
    code: List[str] = []
    examples: List[str] = []

    def flush_code():
        if code:
            examples.extend(['', '```python', *code, '```'])
            code.clear()

    for line in doc.splitlines():
        stripped = line.strip()
        if stripped.startswith('>>>') or (code and stripped and not stripped.startswith(':')):
            code.append(stripped)
            continue
        flush_code()
        match = re.match(r':param (\w+):\s*(.*)', stripped)
        if match:
            params.append(f'- `{match.group(1)}`: {match.group(2)}')
            continue
        match = re.match(r':returns?:\s*(.*)', stripped)
        if match:
            params.append(f'- Returns: {match.group(1)}')
            continue
        if params and stripped and not stripped.startswith(':'):
            params[-1] += ' ' + stripped        # continuation of a :param line
            continue
        out.append(stripped)
    flush_code()
    while out and not out[-1]:
        out.pop()
    if params:
        out.extend(['', *params])
    out.extend(examples)
    while out and not out[0]:
        out.pop(0)
    return out


def _class_link(name: str, links: Links, here: str) -> str:
    return f'[{name}]({links.page(name)})' if name != here else name


def _enum_link(name: str, enums: Dict[str, EnumInfo], links: Links, here: str) -> str:
    owner = enums[name].owner
    if owner is None:
        return f'`{name}`'
    target = f'#{name.lower()}' if owner == here else links.page(owner, name)
    return f'[{name}]({target})'


def cross_references(classes: List[ClassInfo]) -> Dict[str, Dict[str, Set[str]]]:
    """For each class: {other class: names of the fields/methods through which it uses that class}."""
    uses: Dict[str, Dict[str, Set[str]]] = {info.name: {} for info in classes}
    for info in classes:
        for fld in info.fields:
            if fld.target in uses and fld.target != info.name:
                uses[info.name].setdefault(fld.target, set()).add(fld.name)
        for method in info.methods:
            for other in method.returns:
                if other != info.name and other != CORE:
                    uses[info.name].setdefault(other, set()).add(f'{method.name}()')
    return uses


def render_class(info: ClassInfo, classes: List[ClassInfo], enums: Dict[str, EnumInfo], links: Links) -> str:
    out = [GENERATED, '', f'# {info.name}', '']
    meta = [f'`from xurrent import {info.name}`', f'module `xurrent.{info.module}`']
    if info.resource:
        meta.append(f'API resource `/{info.resource}`')
    if info.api_docs:
        meta.append(f'[Xurrent API docs]({info.api_docs})')
    out += [' · '.join(meta), '']
    if info.doc:
        out += render_doc(info.doc) + ['']
    elif info.resource:
        out += [f'A record of the Xurrent `/{info.resource}` resource. Create instances with the class methods '
                f'below (e.g. `{info.name}.get_by_id(connection, id)`); every field of the API response is '
                'available as an attribute.', '']
    out += [f'[Back to the overview]({links.index()})', '']

    if info.name == CORE:
        out += ['## Constructor', '', '```python', info.init_signature, '```', ''] + render_doc(info.init_doc) + ['']
    elif info.fields:
        out += ['## Fields', '',
                'The named arguments of the constructor. Every other field of the API response is set as an '
                'attribute as well.', '',
                '| Field | Type | Default | Converted to |', '|---|---|---|---|']
        for fld in info.fields:
            target = ''
            if fld.target in enums:
                target = _enum_link(fld.target, enums, links, info.name) + ' (unknown values stay text)'
            elif fld.target:
                target = _class_link(fld.target, links, info.name)
            out.append(f"| `{fld.name}` | {('`' + _cell(fld.annotation) + '`') if fld.annotation else ''} "
                       f"| {('`' + _cell(fld.default) + '`') if fld.default else ''} | {target} |")
        out.append('')

    variable = 'x_api_helper' if info.name == CORE else _instance_name(info.name)
    for kind, title in (('class', 'Class methods'), ('static', 'Static methods'), ('instance', 'Methods')):
        methods = [m for m in info.methods if m.kind == kind]
        if not methods:
            continue
        out += [f'## {title}', '']
        for method in methods:
            prefix = info.name if kind != 'instance' else variable
            out += [f'### {method.name}', '', '```python', f'{prefix}.{method.signature}', '```', '']
            out += render_doc(method.doc)
            details = []
            if method.endpoint:
                details.append(f'API: `{method.endpoint}`')
            classes_used = [name for name in method.returns if name not in (CORE, info.name)]
            if classes_used:
                details.append('Uses: ' + ', '.join(_class_link(n, links, info.name) for n in classes_used))
            if method.enums:
                details.append('Enums: ' + ', '.join(_enum_link(n, enums, links, info.name) for n in method.enums))
            if details:
                out += ['', ' · '.join(details)]
            out.append('')

    if info.enums:
        out += ['## Enums', '']
        for name in info.enums:
            enum = enums[name]
            out += [f'### {name}', '']
            if enum.doc:
                out += render_doc(enum.doc) + ['']
            users = sorted({f'{c.name}.{m.name}' for c in classes for m in c.methods if name in m.enums}
                           | {f'{c.name}.{f.name}' for c in classes for f in c.fields if f.target == name})
            if users:
                out += ['Used by: ' + ', '.join(f'`{u}`' for u in users), '']
            out += ['| Value | Description |', '|---|---|']
            out += [f'| `{value}` | {_cell(comment)} |' for value, comment in enum.members]
            out.append('')

    uses = cross_references(classes)
    used_by = {other: sorted(via) for other, targets in uses.items() for target, via in targets.items()
               if target == info.name}
    if uses[info.name] or used_by:
        out += ['## Cross references', '']
        if uses[info.name]:
            out.append('Uses:')
            out += [f'- {_class_link(other, links, info.name)}: ' + ', '.join(f'`{v}`' for v in sorted(via))
                    for other, via in sorted(uses[info.name].items())]
            out.append('')
        if used_by:
            out.append('Used by:')
            out += [f'- {_class_link(other, links, info.name)}: ' + ', '.join(f'`{v}`' for v in via)
                    for other, via in sorted(used_by.items())]
            out.append('')
    return '\n'.join(out).rstrip('\n') + '\n'


def _first_sentence(info: ClassInfo) -> str:
    if info.doc:
        return info.doc.strip().splitlines()[0]
    return ''


def render_index(classes: List[ClassInfo], enums: Dict[str, EnumInfo], links: Links) -> str:
    domain = [c for c in classes if c.name != CORE]
    out = [GENERATED, '', '# xurrent API reference', '',
           'Python SDK for the [Xurrent REST API](https://developer.xurrent.com/v1/). '
           f'Source and usage examples: [README]({REPO_URL}#readme).', '',
           '## Getting started', '',
           f'Every call goes through a [{CORE}]({links.page(CORE)}): it authenticates (API token or OAuth client '
           'credentials), follows the pagination of the API and retries on HTTP 429.', '',
           '```python', 'from xurrent import XurrentApiHelper, Request, PredefinedFilter', '',
           'x_api_helper = XurrentApiHelper("https://api.xurrent.com/v1", "<api token>", "<account>")',
           'open_requests = Request.get_requests(x_api_helper, PredefinedFilter.open, max_results=10)',
           'request = Request.get_by_id(x_api_helper, open_requests[0].id)',
           'notes = request.get_notes(sort="-created_at", max_results=1)', '```', '',
           '## Conventions', '',
           '- `Class.get_by_id(connection, id)` reads one record, `Class.get_<records>(connection, predefinedFilter, '
           'queryfilter)` lists records; `max_results` (where available) stops after that many.',
           '- Predefined filters are enums (e.g. `PredefinedFilter.open` for `/requests/open`); `queryfilter` is a '
           'dict of field filters (`{"subject": "Printer"}`).',
           '- Records are Python objects: the constructor arguments listed on each page plus every other field of '
           'the API response as attributes. References to other records (e.g. `request.requested_by`) become '
           'instances of their class where the page says so.',
           '- Enum fields hold enum members for known values; a value the SDK does not know yet stays a plain '
           'string, so new values in the API do not break loading.',
           '- Write methods (`create`, `update`, `archive`, ...) send the change to the API and return the updated '
           'record.', '',
           '## Classes', '',
           '| Class | API resource | Module | Description |', '|---|---|---|---|']
    for info in domain:
        out.append(f'| [{info.name}]({links.page(info.name)}) | `/{info.resource}` | `xurrent.{info.module}` '
                   f'| {_cell(_first_sentence(info))} |')
    out += ['', f'Core: [{CORE}]({links.page(CORE)}) (connection, `api_call`, `search`, `list_archive`, '
            '`list_trash`, `list_audit_lines`, `bulk_export`, `bulk_import`).', '', '## Enums', '',
            '| Enum | Values | Page |', '|---|---|---|']
    for name in sorted(enums):
        enum = enums[name]
        if enum.owner is None:
            continue
        values = ', '.join(f'`{value}`' for value, _ in enum.members)
        out.append(f'| [{name}]({links.page(enum.owner, name)}) | {values} | {enum.owner} |')
    return '\n'.join(out).rstrip('\n') + '\n'


def render_sidebar(classes: List[ClassInfo], links: Links) -> str:
    out = [f'**[Overview]({links.index()})**', '', f'- [{CORE}]({links.page(CORE)})']
    out += [f'- [{c.name}]({links.page(c.name)})' for c in classes if c.name != CORE]
    return '\n'.join(out) + '\n'


def render_readme_table(classes: List[ClassInfo]) -> str:
    """Class table for README.md; absolute links, because PyPI shows the README too."""
    out = [README_START, '| Class | API resource | Class | API resource |', '|---|---|---|---|']
    domain = [c for c in classes if c.name != CORE]
    half = (len(domain) + 1) // 2
    for left, right in zip(domain[:half], domain[half:] + [None]):
        row = f'| [{left.name}]({REPO_URL}/blob/main/docs/api/{left.name}.md) | `/{left.resource}` |'
        row += (f' [{right.name}]({REPO_URL}/blob/main/docs/api/{right.name}.md) | `/{right.resource}` |'
                if right else ' | |')
        out.append(row)
    out.append(README_END)
    return '\n'.join(out)


def build(wiki: bool = False, src: str = SRC) -> Dict[str, str]:
    """{file name: content} of all pages."""
    classes, enums = read_package(src)
    links = Links(wiki)
    classes.sort(key=lambda c: (c.name != CORE, c.name))
    pages = {f'{info.name}.md': render_class(info, classes, enums, links) for info in classes}
    pages['Home.md' if wiki else 'README.md'] = render_index(classes, enums, links)
    if wiki:
        pages['_Sidebar.md'] = render_sidebar(classes, links)
    return pages


def updated_readme(text: str, src: str = SRC) -> str:
    classes, _ = read_package(src)
    classes.sort(key=lambda c: c.name)
    start, end = text.find(README_START), text.find(README_END)
    if start < 0 or end < 0:
        raise ValueError(f'README.md has no {README_START} ... {README_END} markers')
    return text[:start] + render_readme_table(classes) + text[end + len(README_END):]


def _write(path: str, content: str) -> None:
    with open(path, 'w', encoding='utf-8', newline='\n') as file:
        file.write(content)


def _read(path: str) -> Optional[str]:
    try:
        with open(path, encoding='utf-8', newline='') as file:
            return file.read()
    except FileNotFoundError:
        return None


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument('--check', action='store_true', help='only check that docs/api/ and README.md are current')
    parser.add_argument('--wiki', metavar='DIR', help='write the pages for the GitHub wiki into DIR instead')
    args = parser.parse_args(argv)

    if args.wiki:
        os.makedirs(args.wiki, exist_ok=True)
        for name, content in build(wiki=True).items():
            _write(os.path.join(args.wiki, name), content)
        print(f'wrote {len(build(wiki=True))} wiki pages to {args.wiki}')
        return 0

    pages = build()
    readme = _read(README) or ''
    new_readme = updated_readme(readme)
    stale = [name for name, content in pages.items() if _read(os.path.join(DOCS, name)) != content]
    extra = sorted(set(os.listdir(DOCS)) - set(pages)) if os.path.isdir(DOCS) else []
    if args.check:
        problems = stale + [f'{name} (no longer generated)' for name in extra]
        if new_readme != readme:
            problems.append('README.md (class table)')
        if problems:
            print('Out of date, run python docs/generate_api_docs.py: ' + ', '.join(problems))
            return 1
        print('docs/api/ and README.md are up to date')
        return 0
    os.makedirs(DOCS, exist_ok=True)
    for name in stale:
        _write(os.path.join(DOCS, name), pages[name])
    for name in extra:
        os.remove(os.path.join(DOCS, name))
    if new_readme != readme:
        _write(README, new_readme)
    print(f'{len(stale)} pages written, {len(extra)} removed, README.md '
          f'{"updated" if new_readme != readme else "unchanged"}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
